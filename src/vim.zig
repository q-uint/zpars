//! Vim syntax file generator for zpars grammar formats.
//!
//! Generates `abnf.vim`, `bnf.vim`, `peg.vim`, and `cfg.vim` syntax files
//! based on the same token patterns used by the scanners. Output directory
//! is taken from argv or defaults to `editors/vim/syntax/`.

const std = @import("std");

const Language = struct {
    name: []const u8,
    display: []const u8,
    rules: []const Rule,
};

const Rule = struct {
    group: []const u8,
    kind: Kind,

    const Kind = union(enum) {
        match: []const u8,
        region: Region,
    };

    const Region = struct {
        start: []const u8,
        end: []const u8,
        skip: ?[]const u8 = null,
    };
};

const abnf_rules = [_]Rule{
    .{ .group = "abnfRulename", .kind = .{ .match = "\\<[a-zA-Z][a-zA-Z0-9-]*\\>" } },
    .{ .group = "abnfOperator", .kind = .{ .match = "[=/\\*()\\[\\]]" } },
    .{ .group = "abnfOperator", .kind = .{ .match = "=/" } },
    .{ .group = "abnfString", .kind = .{ .region = .{ .start = "\"", .end = "\"" } } },
    .{ .group = "abnfString", .kind = .{ .match = "%[si]\"[^\"]*\"" } },
    .{ .group = "abnfProse", .kind = .{ .region = .{ .start = "<", .end = ">" } } },
    .{ .group = "abnfNumber", .kind = .{ .match = "%b[01][01.\\-]*" } },
    .{ .group = "abnfNumber", .kind = .{ .match = "%d[0-9][0-9.\\-]*" } },
    .{ .group = "abnfNumber", .kind = .{ .match = "%x[0-9A-Fa-f][0-9A-Fa-f.\\-]*" } },
    .{ .group = "abnfNumber", .kind = .{ .match = "\\<[0-9]\\+\\>" } },
    .{ .group = "abnfComment", .kind = .{ .match = ";.*$" } },
};

const bnf_rules = [_]Rule{
    .{ .group = "bnfRulename", .kind = .{ .region = .{ .start = "<", .end = ">" } } },
    .{ .group = "bnfOperator", .kind = .{ .match = "::=" } },
    .{ .group = "bnfOperator", .kind = .{ .match = "|" } },
};

const peg_rules = [_]Rule{
    .{ .group = "pegIdentifier", .kind = .{ .match = "\\<[a-zA-Z_][a-zA-Z0-9_]*\\>" } },
    .{ .group = "pegOperator", .kind = .{ .match = "<-" } },
    .{ .group = "pegOperator", .kind = .{ .match = "[/&!?*+.]" } },
    .{ .group = "pegString", .kind = .{ .region = .{ .start = "'", .end = "'", .skip = "\\\\." } } },
    .{ .group = "pegString", .kind = .{ .region = .{ .start = "\"", .end = "\"", .skip = "\\\\." } } },
    .{ .group = "pegCharClass", .kind = .{ .region = .{ .start = "\\[", .end = "\\]", .skip = "\\\\." } } },
    .{ .group = "pegComment", .kind = .{ .match = "#.*$" } },
};

const cfg_rules = [_]Rule{
    .{ .group = "cfgIdentifier", .kind = .{ .match = "\\<[a-zA-Z_][a-zA-Z0-9_-]*\\>" } },
    .{ .group = "cfgOperator", .kind = .{ .match = "->" } },
    .{ .group = "cfgOperator", .kind = .{ .match = "|" } },
    .{ .group = "cfgString", .kind = .{ .region = .{ .start = "\"", .end = "\"" } } },
    .{ .group = "cfgString", .kind = .{ .match = "%[si]\"[^\"]*\"" } },
    .{ .group = "cfgNumber", .kind = .{ .match = "%x[0-9A-Fa-f]\\+\\(-[0-9A-Fa-f]\\+\\)\\=" } },
    .{ .group = "cfgComment", .kind = .{ .match = "//.*$" } },
};

const languages = [_]Language{
    .{ .name = "abnf", .display = "ABNF", .rules = &abnf_rules },
    .{ .name = "bnf", .display = "BNF", .rules = &bnf_rules },
    .{ .name = "peg", .display = "PEG", .rules = &peg_rules },
    .{ .name = "cfg", .display = "CFG", .rules = &cfg_rules },
};

const hi_links = [_]struct { suffix: []const u8, target: []const u8 }{
    .{ .suffix = "Rulename", .target = "Type" },
    .{ .suffix = "Identifier", .target = "Type" },
    .{ .suffix = "Operator", .target = "Operator" },
    .{ .suffix = "String", .target = "String" },
    .{ .suffix = "Prose", .target = "String" },
    .{ .suffix = "Number", .target = "Number" },
    .{ .suffix = "Comment", .target = "Comment" },
    .{ .suffix = "CharClass", .target = "Special" },
};

fn writePattern(file: std.fs.File, pat: []const u8) !void {
    for (pat) |c| {
        if (c == '/') {
            _ = try file.write("\\/");
        } else {
            _ = try file.write(&.{c});
        }
    }
}

fn generate(lang: Language, dir: std.fs.Dir) !void {
    var name_buf: [64]u8 = undefined;
    const filename = std.fmt.bufPrint(&name_buf, "{s}.vim", .{lang.name}) catch unreachable;

    const file = try dir.createFile(filename, .{});
    defer file.close();

    try file.writeAll("\" Vim syntax file for ");
    try file.writeAll(lang.display);
    try file.writeAll(" grammars (auto-generated by zpars)\n\" Language: ");
    try file.writeAll(lang.display);
    try file.writeAll("\n\nif exists('b:current_syntax')\n  finish\nendif\n\n");

    for (lang.rules) |rule| {
        switch (rule.kind) {
            .match => |pat| {
                try file.writeAll("syn match ");
                try file.writeAll(rule.group);
                try file.writeAll(" /");
                try writePattern(file, pat);
                try file.writeAll("/\n");
            },
            .region => |reg| {
                try file.writeAll("syn region ");
                try file.writeAll(rule.group);
                try file.writeAll(" start=/");
                try writePattern(file, reg.start);
                try file.writeAll("/ end=/");
                try writePattern(file, reg.end);
                try file.writeAll("/");
                if (reg.skip) |skip| {
                    try file.writeAll(" skip=/");
                    try writePattern(file, skip);
                    try file.writeAll("/");
                }
                try file.writeAll("\n");
            },
        }
    }

    try file.writeAll("\n");

    for (hi_links) |link| {
        for (lang.rules) |rule| {
            if (std.mem.endsWith(u8, rule.group, link.suffix)) {
                try file.writeAll("hi def link ");
                try file.writeAll(rule.group);
                try file.writeAll(" ");
                try file.writeAll(link.target);
                try file.writeAll("\n");
                break;
            }
        }
    }

    try file.writeAll("\nlet b:current_syntax = '");
    try file.writeAll(lang.name);
    try file.writeAll("'\n");
}

pub fn main() !void {
    var args = std.process.args();
    _ = args.next(); // skip program name

    const out_path = args.next() orelse "editors/vim/syntax";

    var dir = std.fs.cwd().makeOpenPath(out_path, .{}) catch |err| {
        std.debug.print("cannot open output directory '{s}': {}\n", .{ out_path, err });
        std.process.exit(1);
    };
    defer dir.close();

    for (&languages) |lang| {
        generate(lang, dir) catch |err| {
            std.debug.print("failed to generate {s}.vim: {}\n", .{ lang.name, err });
            std.process.exit(1);
        };
    }
}
